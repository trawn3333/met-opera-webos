#!/usr/bin/env python3
"""Generic 1.4.2 builder: facts/titles-snark/spec_<slug>.py -> facts/titles/<slug>.json (same rules as mk_idomeneo_141.py).

Spec module defines:
  TITLE, MATCH (catalog names), PERF = {id, date, dockey, prodPremiere}, SCENES = '<slug>-<date>-scenes.json'
  B = [ {k: kicker, t: text, at: scene key (unique substring of one full scene title), sc: 'perf'|'prod'|'all',
         ty: type, src: source file, anchor?, ev: [verbatim evidence], extra?: [(file, [evidence])], attr?: attribution line,
         off?: seconds into the scene, keep?: old fact id this bubble keeps/rewrites} ]
Checks (fails the run): <=20 words, kicker <=32 chars, scene key matches exactly one scene, evidence verbatim in the cached
source(s), every bubble inside its scene, >= GAP seconds between consecutive bubbles. Offsets are automatic unless given:
20 s into the scene (3 s for scenes under 25 s), later bubbles in the same scene 100 s apart, then pushed later to keep GAP.
Usage: python3 facts/titles-snark/mk_title.py <slug> [--dry]
"""
import json, os, re, sys, importlib.util, unicodedata
H = os.path.dirname(os.path.abspath(__file__)); SRC = os.path.join(H, '..', 'sources')
GAP = 60
slug = sys.argv[1]; dry = '--dry' in sys.argv
spec = importlib.util.spec_from_file_location('spec', os.path.join(H, 'spec_%s.py' % slug)); S = importlib.util.module_from_spec(spec); spec.loader.exec_module(S)
sc = json.load(open(os.path.join(H, S.SCENES))); SC = sc['scenes']; DUR = sc.get('duration') or SC[-1]['t'] + 300
def norm(s): return re.sub(r'\s+', ' ', unicodedata.normalize('NFC', str(s)).replace('\u2018', "'").replace('\u2019', "'").replace('\u02bc', "'").replace('\u201c', '"').replace('\u201d', '"').replace('\u2013', '-').replace('\u2014', '-')).strip().lower()
_c = {}
def src(f):
    if f not in _c: _c[f] = norm(open(os.path.join(SRC, f), encoding='utf8').read())
    return _c[f]
def url(f): return re.match(r'URL: (\S+)', open(os.path.join(SRC, f), encoding='utf8').read()).group(1)
SCOPE = {'perf': 'perf:' + S.PERF['id'].replace('-', '')[:8], 'prod': 'production:' + S.PERF['prodPremiere'], 'all': 'all'}
errs = []; rows = []; per = {}
for i, b in enumerate(S.B):
    n = '%s-%02d' % (slug[:4], i + 1)
    words = len(re.findall(r"[\w’'][\w’'\-.]*", b['t']))
    if words > 20: errs.append('%s: %d words' % (n, words))
    if len(b['k']) > 32: errs.append(n + ': kicker too long')
    hits = [j for j, s in enumerate(SC) if b['at'].lower() in s['title'].lower()]
    if len(hits) != 1: errs.append('%s: scene key %r matches %d scenes' % (n, b['at'], len(hits))); continue
    j = hits[0]
    if not os.path.exists(os.path.join(SRC, b['src'])): errs.append(n + ': no source ' + b['src']); continue
    for e in b['ev']:
        if norm(e) not in src(b['src']): errs.append('%s: evidence not in %s: %s' % (n, b['src'], e[:70]))
    extra = []
    for f, evs in b.get('extra', []):
        if not os.path.exists(os.path.join(SRC, f)): errs.append(n + ': no source ' + f); continue
        for e in evs:
            if norm(e) not in src(f): errs.append('%s: evidence not in %s: %s' % (n, f, e[:70]))
        extra.append({'source': f, 'url': url(f), 'evidence': list(evs)})
    rx = ('^' + re.escape(SC[j]['title']) + '$') if b['sc'] == 'perf' else re.escape(b['at'].strip()).replace('\\ ', ' ')
    f = {'id': n, 'type': b['ty'], 'kicker': b['k'], 'sceneMatch': rx, 'sceneOnly': True, 'scope': SCOPE[b['sc']], 'text': b['t']}
    if b.get('attr'): f['attribution'] = b['attr']
    f['source'] = b['src']
    if b.get('anchor'): f['anchor'] = b['anchor']
    f['evidence'] = list(b['ev'])
    if extra: f['extraSources'] = extra
    if b.get('keep'): f['keeps'] = b['keep']
    rows.append([f, j, b.get('off')])
if errs: print('\n'.join(errs)); sys.exit(1)
end = lambda j: SC[j + 1]['t'] if j + 1 < len(SC) else DUR
# offsets
cnt = {}
for r in rows:
    f, j, off = r
    k = cnt.get(j, 0); cnt[j] = k + 1
    ln = end(j) - SC[j]['t']
    r.append(SC[j]['t'] + (off if off is not None else (3 if ln < 25 else 20 + k * 100)))
rows.sort(key=lambda r: r[3])
prev = -1e9
for r in rows:
    f, j, off, at = r
    if at < prev + GAP: at = prev + GAP
    if at + 12 > end(j): errs.append('%s: no room in scene %r (at %d, scene ends %d)' % (f['id'], SC[j]['title'], at, end(j)))
    r[3] = at; f['offset'] = int(round(at - SC[j]['t'])); prev = at
if errs: print('\n'.join(errs)); sys.exit(1)
# sceneMatch check for loose regexes
for f, j, off, at in rows:
    m = [s['title'] for s in SC if re.search(f['sceneMatch'], s['title'], re.I)]
    if m != [SC[j]['title']]: print('REGEX', f['id'], f['sceneMatch'], m); sys.exit(1)
doc = {'title': S.TITLE, 'match': S.MATCH, 'gap': GAP,
       'note': '1.4.2: Pop-Up Video-style bubbles timed to the Met HD %s scene markers (%s). Generated by facts/titles-snark/mk_title.py from spec_%s.py.' % (S.PERF['date'], S.PERF['id'], slug),
       'facts': [r[0] for r in rows]}
gaps = [rows[i][3] - rows[i - 1][3] for i in range(1, len(rows))]
print('%s: %d bubbles, min gap %ds, scopes %s' % (slug, len(rows), min(gaps), {k: sum(1 for r in rows if r[0]['scope'] == v) for k, v in SCOPE.items()}))
if not dry:
    out = os.path.join(H, '..', 'titles', slug + '.json')
    json.dump(doc, open(out, 'w'), ensure_ascii=False, indent=1); open(out, 'a').write('\n')
