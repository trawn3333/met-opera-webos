// Builds the pop-up facts from the source of truth (facts/titles/*.json):
//  1. verifies every fact (verify.js: evidence must appear verbatim in the cached source; sourceUrl required) - rejects fail the build
//  2. writes facts/dist/<slug>.json (what the Worker serves) and facts/dist/index.json
//  3. writes app/src/userscript/facts/factsData.js: INDEX (slug -> title match names, all titles) + BUNDLED (top titles, offline fallback)
// Usage: node facts/build.js
const fs = require('fs'), path = require('path');
const { verifyTitle } = require('./verify');
const BUNDLE = ['idomeneo', 'boheme', 'tosca', 'carmen', 'traviata', 'butterfly', 'aida', 'figaro', 'flute', 'giovanni'];
const T = { composer: 'c', artist: 'a', premiere: 'p', critic: 'r', history: 'h', staging: 's', blooper: 'b', music: 'm' };
const dist = path.join(__dirname, 'dist');
fs.mkdirSync(dist, { recursive: true });
const index = {}, bundled = {}, stats = [];
let bad = 0;
for (const f of fs.readdirSync(path.join(__dirname, 'titles')).filter((x) => /\.json$/.test(x)).sort()) {
  const slug = f.replace(/\.json$/, '');
  const r = verifyTitle(path.join(__dirname, 'titles', f));
  for (const b of r.bad) { console.error('REJECT', b.id, b.why.join('; ')); bad++; }
  // compact rows: [id, type, sceneMatch|'', scope, text, attribution, sourceUrl, kicker?, offset?, sceneOnly?]
  // (1.4.1 fields 7-9 are optional: trailing ones are omitted, so older titles' rows are unchanged; 1.4.0 apps ignore them)
  const rows = r.ok.map((x) => {
    const row = [x.id, T[x.type], x.sceneMatch || '', x.scope === 'all' ? '' : x.scope, x.text, x.attribution, encodeURI(decodeURI(x.sourceUrl)),
      x.kicker || '', typeof x.offset === 'number' ? x.offset : null, x.sceneOnly ? 1 : 0];
    while (row.length > 7 && (row[row.length - 1] === '' || row[row.length - 1] === null || row[row.length - 1] === 0)) row.pop();
    return row;
  });
  const doc = { v: 1, slug, title: r.title, match: r.match, facts: rows };
  if (r.gap) doc.gap = r.gap;
  fs.writeFileSync(path.join(dist, slug + '.json'), JSON.stringify(doc));
  index[slug] = r.match;
  if (BUNDLE.indexOf(slug) >= 0) bundled[slug] = doc;
  stats.push({ slug, title: r.title, facts: rows.length, scene: rows.filter((x) => x[2]).length, bytes: JSON.stringify(doc).length });
}
if (bad) { console.error(bad + ' fact(s) rejected: fix or drop them.'); process.exit(1); }
fs.writeFileSync(path.join(dist, 'index.json'), JSON.stringify({ v: 1, titles: index }));
const out = path.join(__dirname, '../app/src/userscript/facts/factsData.js');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, '// GENERATED by facts/build.js from facts/titles/*.json - do not edit.\n' +
  '// INDEX: slug -> title names to match; BUNDLED: offline copy for the top titles (others are fetched from the Worker).\n' +
  'export var INDEX = ' + JSON.stringify(index) + ';\nexport var BUNDLED = ' + JSON.stringify(bundled) + ';\n');
const total = stats.reduce((a, s) => a + s.facts, 0), bytes = stats.reduce((a, s) => a + s.bytes, 0);
for (const s of stats) console.log(s.title.padEnd(26), String(s.facts).padStart(3), 'facts', String(s.scene).padStart(3), 'scene-tied', String(s.bytes).padStart(6), 'B', BUNDLE.indexOf(s.slug) >= 0 ? '(bundled)' : '');
console.log('titles', stats.length, 'facts', total, 'dist bytes', bytes, 'bundled bytes', fs.statSync(out).size);
