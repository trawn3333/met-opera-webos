// matches.json (archive-crawl.js) -> src/userscript/cast/creditsData.js (bundled) + stats.
// Acceptance: performance matched in the archive by title + exact date AND a Met "New Production" premiere of that
// archive title on or before the performance date whose record lists production credits.
// Caution for the old house: before 1966-09 the archive rarely tags new productions, so a production premiered before 1966 is
// only linked when its production premiered in the same or previous 10 seasons (otherwise left blank).
const fs = require('fs');
const M = JSON.parse(fs.readFileSync('/workspace/met/archive/matches.json', 'utf8'));
const OLD_GAP_YEARS = 10;
const prods = [], pidx = {}, perf = {};
const st = { total: 0, operaish: 0, matched: 0, credited: 0, skippedOld: 0, noNP: 0, npNoCredits: 0, noMatch: 0, noEvent: 0 };
const unmatched = [];
for (const r of M.res) {
  st.total++;
  if (r.status === 'matched') st.matched++;
  else { if (r.status === 'no-archive-event') st.noEvent++; else st.noMatch++; unmatched.push(r.d + ' ' + r.opera + ' [' + r.status + '] ' + (r.day || []).join(' | ')); continue; }
  if (!r.prod) { st.noNP++; continue; }
  if (!r.prod.credits.length) { st.npNoCredits++; continue; }
  const gap = (new Date(r.d) - new Date(r.prod.premiere)) / 3.15576e10;
  if (r.prod.premiere < '1966-09-01' && gap > OLD_GAP_YEARS) { st.skippedOld++; continue; }
  const key = r.prod.dockey;
  if (pidx[key] === undefined) { pidx[key] = prods.length; prods.push([r.prod.premiere, r.prod.credits, r.prod.cid]); }
  const k = r.id.replace(/-/g, '').slice(0, 10);
  if (perf[k] !== undefined) throw new Error('id prefix collision ' + k);
  perf[k] = pidx[key];
  st.credited++;
}
fs.writeFileSync(__dirname + '/../src/userscript/cast/creditsData.js',
  '// GENERATED by tools/build-credits.js from the Met Opera Archives (archives.metopera.org), ' + M.at.slice(0, 10) + '. Do not edit.\n' +
  '// PRODS: [production premiere date, [[role as listed, name]], archive CID]; PERF: performance id prefix -> PRODS index\n' +
  'export var PRODS = ' + JSON.stringify(prods) + ';\nexport var PERF = ' + JSON.stringify(perf) + ';\n');
fs.writeFileSync('/workspace/met/archive/unmatched.txt', unmatched.join('\n') + '\n');
console.log(JSON.stringify(st), 'productions', prods.length);
